"""Ship current, hash-verified Hunyuan exports for portable source identities."""
from pathlib import Path
import argparse, hashlib, json, shutil

ROOT=Path(__file__).resolve().parents[2]
BASE=ROOT/'src/prototype/assets'
LEGACY={'CHEST':'chest-v1.glb','LAMP':'lamp-v1.glb','SWORD':'sword-v1.glb'}
def sha(path): return hashlib.sha256(path.read_bytes()).hexdigest()

def sync(check=False):
 catalog=json.loads((ROOT/'games/zork2/assets/catalog.json').read_text())
 entries=[]
 missing=[]
 for obj in catalog['objects']:
  if obj['kind']!='prop' or 'TAKEBIT' not in obj['flags']: continue
  folder=ROOT/'out/asset-production'/obj['id']
  if not (folder/'candidate.json').exists():
   missing.append(obj['sourceIdentity']);continue
  candidate=json.loads((folder/'candidate.json').read_text())
  assert candidate['sourceIdentity']==obj['sourceIdentity']
  assert candidate['sourceHash']==obj['sourceHash'] and candidate['briefHash']==obj['briefHash'], obj['id']
  assert sha(folder/'candidate.glb')==candidate['sha256'], obj['id']
  path=folder/'candidate.glb';record=candidate
  for name in ['animation','finished']:
   report=folder/(name+'.json')
   if not report.exists(): continue
   refined=json.loads(report.read_text())
   if refined.get('inputMeshSha256')!=candidate['sha256']: continue
   selected=folder/refined['file']
   assert sha(selected)==refined['sha256'], obj['id']
   path=selected;record=refined
  destination=BASE/LEGACY.get(obj['sourceIdentity'],'props/'+obj['id']+'.glb')
  if check: assert destination.exists() and sha(destination)==record['sha256'], obj['id']
  else:
   destination.parent.mkdir(parents=True,exist_ok=True)
   if not destination.exists() or sha(destination)!=record['sha256']: shutil.copy2(path,destination)
  entries.append({'id':obj['sourceIdentity'],'file':str(destination.relative_to(BASE)),'source':str(path.relative_to(ROOT)), 'sha256':sha(destination),'sourceHash':candidate['sourceHash'],'briefHash':candidate['briefHash'],'pipeline':candidate['pipeline'],'sizeMetres':candidate['sizeMetres']})
 manifest={'format':'zxr-movable-props-v1','selection':'Current candidate hash; prefer matching finished, then animated exports. Never select raw or rejected meshes.','assets':entries,'missing':missing}
 path=BASE/'movable-props.json'
 # Browser-safe metadata has no filesystem or URL dependencies.
 definitions=[{'id':o['sourceIdentity'],'sizeMetres':o['estimatedSizeMetres']} for o in catalog['objects'] if o['kind']=='prop' and 'TAKEBIT' in o['flags']]
 source='// Generated by tools/assets/sync-movable-props.py. Sizes are presentation estimates.\nexport const movablePropDefinitions = '+json.dumps(definitions,indent=2)+' as const;\n'
 source+='export const movablePropFiles = '+json.dumps({e['id']:e['file'] for e in entries},indent=2)+' as const;\n'
 metadata=ROOT/'src/prototype/movable-props.generated.ts'
 if check:
  assert json.loads(path.read_text())==manifest
  assert metadata.read_text()==source
 else:
  path.write_text(json.dumps(manifest,indent=2)+'\n');metadata.write_text(source)
 print(json.dumps({'generatedMovableProps':len(entries),'withoutGeneratedModel':missing}))

if __name__=='__main__':
 parser=argparse.ArgumentParser();parser.add_argument('--check',action='store_true');args=parser.parse_args();sync(args.check)
